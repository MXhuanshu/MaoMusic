const crypto = require('crypto')
const fs = require('fs')
const buf = fs.readFileSync('build/MaoMusic-2.0.4-x64-setup.exe')
const hash = crypto.createHash('sha512').update(buf).digest('base64')
const yml = fs.readFileSync('build/latest.yml', 'utf8')
const m = /sha512:\s*(\S+)/.exec(yml)
console.log('exe   =', hash)
console.log('yml   =', m ? m[1] : '(not found)')
console.log('match =', m ? hash === m[1] : false)
